#!/usr/bin/env node
'use strict';
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
const { execFileSync } = require('node:child_process');
const { promotionPlan } = require('./promotion-plan');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'pk-plan-'));
const git = (...args) => execFileSync('git', args, { cwd: tmp, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
const write = (name, content) => { const p = path.join(tmp, name); fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, content); };
let count = 0;
const check = (name, fn) => { fn(); count++; console.log(`✓ ${name}`); };
try {
  git('init', '-q', '-b', 'master'); git('config', 'user.name', 'Test'); git('config', 'user.email', 'test@example.invalid');
  write('.gitignore', 'outputs/\n.history/\n');
  write('processes/team-a-report.md', 'base'); write('context/team-a-delete.md', 'delete'); write('processes/general.md', 'common');
  git('add', '.'); git('commit', '-qm', 'base'); git('branch', 'my'); git('checkout', '-qb', 'team-a');
  write('processes/team-a-report.md', 'target'); write('processes/team-a-target-only.md', 'target only');
  git('add', '.'); git('commit', '-qm', 'destination advanced'); git('checkout', '-q', 'my');
  write('processes/team-a-report.md', 'source'); write('processes/team-a-new.md', 'new');
  write('context/team-a-staged.md', 'staged'); git('add', 'context/team-a-staged.md');
  fs.unlinkSync(path.join(tmp, 'context/team-a-delete.md'));
  write('context/my-preferences.md', 'private'); write('context/team-b-private.md', 'another team'); write('TEAM.md', 'administrative');
  write('processes/general.md', 'common changed'); write('outputs/private.txt', 'private');
  const before = git('status', '--porcelain=v1'); const head = git('rev-parse', 'HEAD');
  const plan = promotionPlan(tmp, 'team-a');
  check('new files only at target are not deleted', () => assert.ok(![...plan.candidates, ...plan.conflicts].some(x => x.path === 'processes/team-a-target-only.md')));
  check('concurrent edit is a conflict', () => assert.ok(plan.conflicts.some(x => x.path === 'processes/team-a-report.md')));
  check('untracked scoped file is a candidate', () => assert.ok(plan.candidates.some(x => x.path === 'processes/team-a-new.md' && x.operation === 'add')));
  check('staged changes are included', () => assert.ok(plan.candidates.some(x => x.path === 'context/team-a-staged.md')));
  check('deletion is explicit', () => assert.ok(plan.candidates.some(x => x.path === 'context/team-a-delete.md' && x.operation === 'delete')));
  check('personal and other-team files excluded', () => assert.ok(plan.excluded.some(x => x.path === 'context/my-preferences.md') && plan.excluded.some(x => x.path === 'context/team-b-private.md')));
  check('common files excluded from team', () => assert.ok(plan.excluded.some(x => x.path === 'processes/general.md')));
  check('admin file is marked for explicit choice', () => assert.ok(plan.candidates.some(x => x.path === 'TEAM.md' && x.administrative)));
  check('ignored results are absent', () => assert.ok(!JSON.stringify(plan).includes('outputs/private.txt')));
  check('no mutation to HEAD, index or working tree', () => { assert.equal(git('status', '--porcelain=v1'), before); assert.equal(git('rev-parse', 'HEAD'), head); });
  const next = promotionPlan(tmp, 'master');
  check('team and admin files excluded from master', () => assert.ok(!next.candidates.some(x => x.path.includes('team-a-') || x.path === 'TEAM.md')));
  check('snapshot hashes and pinned target are present', () => { assert.match(plan.targetCommit, /^[0-9a-f]+$/); assert.match(plan.candidates.find(x => x.operation === 'add').source.sha256, /^[0-9a-f]{64}$/); });
  console.log(`Promotion planning: ${count} passed.`);
} finally { fs.rmSync(tmp, { recursive: true, force: true }); }
